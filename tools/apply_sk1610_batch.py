def main() -> None:
    data = json.loads(ANN.read_text())
    by_id = {entry["paragraphId"]: entry for entry in data["entries"]}
    missing = [pid for pid in UPDATES if pid not in by_id]
    if missing:
        raise SystemExit(f"missing paragraph ids: {missing}")
    for pid, payload in UPDATES.items():
        entry = by_id[pid]
        entry["kind"] = payload["kind"]
        entry["vernacular"] = payload["vernacular"]
        entry["terms"] = payload["terms"]
        entry["notes"] = list(NOTES)
        entry["review"] = "source-reviewed"
        entry["verified"] = False
        if "subsections" in payload:
            entry["subsections"] = payload["subsections"]
        elif "subsections" in entry:
            del entry["subsections"]
        if "原文：" in entry["vernacular"]:
            raise SystemExit(f"refused to keep 原文 dump: {pid}")
    ANN.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n")
    print(f"updated {len(UPDATES)} entries in {ANN}")


if __name__ == "__main__":
    main()
